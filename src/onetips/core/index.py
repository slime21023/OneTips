from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass
from html import unescape
from typing import Final

from onetips.core.config import ProjectConfig, is_path_slug, is_slug
from onetips.core.errors import DataError
from onetips.core.section import SECTION_KEYS
from onetips.core.tip import Tip

GENERATED_NOTICE: Final = "<!-- Generated by `onetips index`. Do not edit by hand. -->"
COUNT_SUFFIX: Final = " tips. Each row links to one tip in `references/`."
TITLE_SUFFIX: Final = " Tips — Index"
TABLE_HEADER: Final = "|ID|Title|Summary|Tags|Applies to|Snippets|"
TABLE_DIVIDER: Final = "|---|---|---|---|---|---|"
_ROW_LINK = re.compile(r"\[([a-z0-9]+(?:-[a-z0-9]+)*)\]\(references/\1\.md\)")
_CELL_DIVIDER = re.compile(r"(?<!\\)\|")
_COUNT = re.compile(r"0|[1-9][0-9]*")
_SNIPPETS = re.compile(r"tested [0-9]+, compiled [0-9]+, unverified [0-9]+")


@dataclass(frozen=True)
class IndexRow:
    """One INDEX.md row; field names match the `find --json` contract (PROPOSAL §11.1)."""

    id: str
    title: str
    summary: str
    category: str
    tags: tuple[str, ...]
    applies_to: str
    path: str


@dataclass(frozen=True)
class Catalog:
    sections: dict[str, str]
    rows: list[IndexRow]


class CatalogError(DataError):
    def __init__(self, line: int, message: str) -> None:
        super().__init__(message)
        self.line = line


class _Lines:
    def __init__(self, text: str) -> None:
        self.lines = text.split("\n")
        self.offset = 0

    @property
    def line(self) -> int:
        """1-based line number of the line most recently returned by `read()`."""
        return self.offset

    def read(self) -> str:
        if self.offset >= len(self.lines) - 1:
            raise CatalogError(self.offset + 1, "unexpected end of index")
        line = self.lines[self.offset]
        self.offset += 1
        return line

    def expect(self, text: str) -> None:
        if self.read() != text:
            raise CatalogError(self.line, f"expected {text!r}")

    def next_is(self, text: str) -> bool:
        return not self.done() and self.lines[self.offset] == text

    def done(self) -> bool:
        return self.offset == len(self.lines) - 1


def _parse_row(text: str, category: str, line: int) -> IndexRow:
    fields = _CELL_DIVIDER.split(text)
    if len(fields) != 8 or fields[0] or fields[-1]:
        raise CatalogError(line, "expected six table cells bounded by pipes")
    _, raw_link, raw_title, raw_summary, raw_tags, raw_versions, raw_snippets, _ = fields
    link = _ROW_LINK.fullmatch(raw_link)
    if link is None:
        raise CatalogError(line, "expected a canonical references/<id>.md link")
    tip_id = link[1]
    if not is_path_slug(tip_id):
        raise CatalogError(line, "tip id is not a portable path identifier")
    title = unescape(raw_title.replace(r"\|", "|"))
    summary = unescape(raw_summary.replace(r"\|", "|"))
    if not title.strip() or not summary.strip():
        raise CatalogError(line, "title and summary must be nonempty")
    tags = tuple(raw_tags.split(", "))
    if any(not is_slug(tag, limit=64) for tag in tags):
        raise CatalogError(line, "tags must be comma-space-separated identifiers")
    if not _SNIPPETS.fullmatch(raw_snippets):
        raise CatalogError(line, "invalid snippet counts")
    versions = unescape(raw_versions.replace(r"\|", "|"))
    return IndexRow(tip_id, title, summary, category, tags, versions, f"references/{tip_id}.md")


def _parse_header(lines: _Lines) -> tuple[str, int]:
    """Read the notice, title and tip count; return the declared count and its line number."""
    lines.expect(GENERATED_NOTICE)
    title = lines.read()
    if not title.startswith("# ") or not title.endswith(TITLE_SUFFIX) or not title[2 : -len(TITLE_SUFFIX)].strip():
        raise CatalogError(lines.line, "expected a domain index title")
    lines.expect("")
    count_text = lines.read()
    count = count_text.removesuffix(COUNT_SUFFIX)
    if count == count_text or not _COUNT.fullmatch(count):
        raise CatalogError(lines.line, "invalid tip count")
    return count, lines.line


def _parse_sections(lines: _Lines) -> dict[str, str]:
    lines.expect("")
    lines.expect("### Sections")
    lines.expect("")
    sections: dict[str, str] = {}
    section_titles: set[str] = set()
    for key in SECTION_KEYS:
        prefix = f"- `{key}`: "
        entry = lines.read()
        if not entry.startswith(prefix):
            raise CatalogError(lines.line, f"expected {key!r} section mapping")
        section_title = unescape(entry[len(prefix) :])
        if not section_title.strip() or section_title.splitlines() != [section_title] or section_title in section_titles:
            raise CatalogError(lines.line, "section titles must be nonempty, distinct single lines")
        sections[key] = section_title
        section_titles.add(section_title)
    return sections


def _parse_category_heading(lines: _Lines, seen: set[str]) -> str:
    lines.expect("")
    group = lines.read()
    category, separator, display = group.removeprefix("## ").partition(" — ")
    if not group.startswith("## ") or not separator or not is_slug(category) or not display.strip():
        raise CatalogError(lines.line, "invalid category heading")
    if category in seen:
        raise CatalogError(lines.line, f"duplicate category {category!r}")
    return category


def _parse_table(lines: _Lines, category: str, ids: set[str]) -> list[IndexRow]:
    lines.expect("")
    lines.expect(TABLE_HEADER)
    lines.expect(TABLE_DIVIDER)
    rows: list[IndexRow] = []
    while True:
        row = _parse_row(lines.read(), category, lines.line)
        if row.id in ids:
            raise CatalogError(lines.line, f"duplicate tip id {row.id!r}")
        ids.add(row.id)
        rows.append(row)
        if lines.done() or lines.next_is(""):
            return rows


def parse_catalog(text: str) -> Catalog:
    if not text.endswith("\n"):
        raise CatalogError(text.count("\n") + 1, "index must end with a newline")
    lines = _Lines(text)
    count, count_line = _parse_header(lines)
    sections = _parse_sections(lines)
    rows: list[IndexRow] = []
    categories: set[str] = set()
    ids: set[str] = set()
    while not lines.done():
        category = _parse_category_heading(lines, categories)
        categories.add(category)
        rows.extend(_parse_table(lines, category, ids))
    if count != str(len(rows)):
        raise CatalogError(count_line, f"index declares {count} tips but contains {len(rows)} rows")
    return Catalog(sections, rows)


def find_rows(
    catalog: Catalog,
    tip_id: str | None,
    category: str | None,
    tag: str | None,
    keyword: str | None,
) -> list[IndexRow]:
    folded = keyword.casefold() if keyword is not None else None
    return [
        row
        for row in catalog.rows
        if (tip_id is None or row.id == tip_id)
        and (category is None or row.category == category)
        and (tag is None or tag in row.tags)
        and (folded is None or folded in row.title.casefold() or folded in row.summary.casefold())
    ]


_MARKUP = str.maketrans(
    {
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        "`": "&#96;",
        "\\": "&#92;",
        "[": "&#91;",
        "]": "&#93;",
        "*": "&#42;",
        "_": "&#95;",
        "~": "&#126;",
        "#": "&#35;",
    }
)


def _display(text: str) -> str:
    return text.translate(_MARKUP)


def _cell(text: str) -> str:
    return _display(text).replace("|", r"\|")


def render_index_header(config: ProjectConfig, count: int) -> str:
    return (
        f"{GENERATED_NOTICE}\n"
        f"# {_display(config.domain)}{TITLE_SUFFIX}\n\n"
        f"{count}{COUNT_SUFFIX}\n\n"
        "### Sections\n\n" + "\n".join(f"- `{key}`: {_display(config.sections[key])}" for key in SECTION_KEYS) + "\n"
    )


def render_index(config: ProjectConfig, tips: list[Tip]) -> str:
    groups: dict[str, list[Tip]] = {category: [] for category in config.categories}
    for tip in tips:
        groups[tip.metadata.category].append(tip)
    lines = [render_index_header(config, len(tips)).removesuffix("\n")]
    for category, group in groups.items():
        if not group:
            continue
        lines.extend(("", f"## {category} — {_display(config.categories[category])}", "", TABLE_HEADER, TABLE_DIVIDER))
        for tip in sorted(group, key=lambda entry: entry.metadata.id):
            metadata = tip.metadata
            counts = Counter(fence.snippet.status for fence in tip.document.fences)
            versions = "; ".join(f"{subject} {version}" for subject, version in metadata.applies_to.items())
            fields = (
                f"[{metadata.id}](references/{metadata.id}.md)",
                _cell(tip.title),
                _cell(metadata.summary),
                ", ".join(metadata.tags),
                _cell(versions),
                f"tested {counts['tested']}, compiled {counts['compiled']}, unverified {counts['unverified']}",
            )
            lines.append("|" + "|".join(fields) + "|")
    return "\n".join(lines) + "\n"
